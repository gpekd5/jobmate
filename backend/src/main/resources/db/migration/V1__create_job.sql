CREATE TABLE job (
    job_id BIGINT NOT NULL AUTO_INCREMENT,
    source VARCHAR(30) NOT NULL,
    external_job_id VARCHAR(200) COLLATE utf8mb4_bin NULL,
    company_name VARCHAR(200) NOT NULL,
    title VARCHAR(300) NOT NULL,
    job_role VARCHAR(100) NULL,
    region VARCHAR(100) NULL,
    employment_type VARCHAR(100) NULL,
    experience_text VARCHAR(300) NULL,
    education_text VARCHAR(300) NULL,
    salary_text VARCHAR(300) NULL,
    original_url VARCHAR(2000) NULL,
    posted_at DATETIME(6) NULL,
    deadline_at DATETIME(6) NULL,
    active BIT NOT NULL,
    responsibilities JSON NULL,
    required_qualifications JSON NULL,
    preferred_qualifications JSON NULL,
    skills JSON NULL,
    work_conditions JSON NULL,
    detail_availability VARCHAR(30) NOT NULL,
    detail_source VARCHAR(30) NOT NULL,
    detail_extracted_at DATETIME(6) NULL,
    last_collected_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    job_version BIGINT NOT NULL,
    lock_version BIGINT NOT NULL,
    PRIMARY KEY (job_id),
    CONSTRAINT uk_job_source_external_id UNIQUE (source, external_job_id),
    INDEX idx_job_posted (posted_at, job_id),
    INDEX idx_job_deadline (deadline_at, job_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
